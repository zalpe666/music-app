<?php

use Illuminate\Support\Facades\Route;
use App\Http\Controllers\SongController;

/*
|--------------------------------------------------------------------------
| Admin Panel
|--------------------------------------------------------------------------
*/

Route::prefix('admin')
    ->middleware([
        'auth',
    ])
    ->group(function () {

        /*
        |--------------------------------------------------------------------------
        | Dashboard
        |--------------------------------------------------------------------------
        */

        Route::view(
            '/dashboard',
            'admin.dashboard'
        );

        /*
        |--------------------------------------------------------------------------
        | Deezer Search API
        |--------------------------------------------------------------------------
        */

        Route::get(
            '/songs/search',
            [SongController::class, 'search']
        )->name('songs.search');

        /*
        |--------------------------------------------------------------------------
        | Songs CRUD
        |--------------------------------------------------------------------------
        */

        Route::resource(
            'songs',
            SongController::class
        );
    });
